"""Install/start Ollama, pull the default local model, write `.env`."""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

from absencecritic.adapters.llm.openai_compat import OLLAMA_BASE_URL, OLLAMA_DEFAULT_MODEL
from absencecritic.envfile import parse_env_file
from absencecritic.paths import repo_root

OLLAMA_HOST = "http://127.0.0.1:11434"


def _ollama_bin() -> str | None:
    found = shutil.which("ollama")
    if found:
        return found
    extra = [
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Ollama" / "ollama.exe",
        Path(r"C:\Program Files\Ollama\ollama.exe"),
        Path("/usr/local/bin/ollama"),
        Path.home() / ".ollama" / "bin" / "ollama",
        Path.home() / ".local" / "bin" / "ollama",
    ]
    for path in extra:
        if path.is_file():
            return str(path)
    return None


def _run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=True, **kwargs)


def _install_ollama() -> None:
    system = sys.platform
    if system == "win32":
        winget = shutil.which("winget")
        if not winget:
            raise RuntimeError(
                "Ollama is not installed and winget was not found. "
                "Install from https://ollama.com/download then re-run."
            )
        _run(
            [
                winget,
                "install",
                "-e",
                "--id",
                "Ollama.Ollama",
                "--accept-package-agreements",
                "--accept-source-agreements",
            ]
        )
        return
    if system == "darwin":
        brew = shutil.which("brew")
        if brew:
            _run([brew, "install", "ollama"])
            return
        raise RuntimeError(
            "Ollama is not installed. Install Homebrew or download https://ollama.com/download"
        )
    curl = shutil.which("curl")
    if not curl:
        raise RuntimeError(
            "Ollama is not installed. Install curl or download https://ollama.com/download"
        )
    subprocess.run(
        f"{curl} -fsSL https://ollama.com/install.sh | sh",
        shell=True,
        check=True,
    )


def _ollama_up() -> bool:
    try:
        with urllib.request.urlopen(OLLAMA_HOST + "/api/tags", timeout=2) as resp:
            return resp.status == 200
    except (urllib.error.URLError, TimeoutError, OSError):
        return False


def _ensure_server(ollama: str) -> None:
    if _ollama_up():
        return
    print("Starting ollama serve ...", flush=True)
    subprocess.Popen(
        [ollama, "serve"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    for _ in range(30):
        if _ollama_up():
            return
        time.sleep(1)
    raise RuntimeError(
        "Ollama did not start on 127.0.0.1:11434. Start the Ollama app and re-run."
    )


def _write_env(model: str) -> Path:
    path = repo_root() / ".env"
    existing = parse_env_file(path)
    existing.update(
        {
            "ABSENCECRITIC_PROVIDER": "ollama",
            "OPENAI_BASE_URL": OLLAMA_BASE_URL,
            "OPENAI_API_KEY": existing.get("OPENAI_API_KEY") or "ollama",
            "ABSENCECRITIC_MODEL": model,
        }
    )
    lines = [
        "# Copyright 2026 Guzino (https://github.com/guzino)",
        "# SPDX-License-Identifier: Apache-2.0",
        "# Generated by absencecritic-setup. Do not commit.",
        "",
    ]
    for key, value in existing.items():
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    del argv
    model = os.environ.get("ABSENCECRITIC_OLLAMA_MODEL") or OLLAMA_DEFAULT_MODEL
    ollama = _ollama_bin()
    if not ollama:
        print("Ollama not found; installing ...", flush=True)
        _install_ollama()
        ollama = _ollama_bin()
        if not ollama:
            raise RuntimeError(
                "Ollama installed but not on PATH. Open a new terminal and re-run "
                "python -m absencecritic.adapters.cli.setup_ollama"
            )
    _ensure_server(ollama)
    _run([ollama, "pull", model])
    env_path = _write_env(model)
    print(f"Wrote {env_path}")
    print("Local model ready. Examples:")
    print(f"  absencecritic --provider ollama \"What works for launching a startup?\"")
    print("  python eval/run_eval.py --provider ollama")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
